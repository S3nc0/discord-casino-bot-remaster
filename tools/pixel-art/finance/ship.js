// sprites: one legend of tokens shared by all of them (they look the same in both themes)
const tokChars = new Map();
const tcode = (px) => {
  if (!(px >>> 24)) return '.';
  const t = RGB2TOK.get(px);
  if (!t) throw new Error('sprite colour is not a palette token');
  if (!tokChars.has(t)) tokChars.set(t, CHARS[tokChars.size]);
  return tokChars.get(t);
};
const sprite = (b) =>
  Array.from({ length: b.h }, (_, y) =>
    Array.from({ length: b.w }, (_, x) => tcode(b.px[y * b.w + x])).join(''),
  );
const coins = Object.fromEntries(Object.entries(COINS).map(([k, f]) => [k, sprite(f())]));
const gavel = gavelFrames().map(sprite);
const spin = spinFrames().map(sprite);
// badge shapes as ramp steps 0..4 (dark to light), coloured by the hue at run time
const shapes = Object.fromEntries(
  BADGE_SHAPES.map((s) => {
    const b = badge(s, 'farm', 'red');
    const ramp = BADGE_RAMPS.red;
    return [
      s,
      Array.from({ length: b.h }, (_, y) =>
        Array.from({ length: b.w }, (_, x) => {
          const px = b.px[y * b.w + x];
          if (!(px >>> 24)) return '.';
          const k = ramp.indexOf(RGB2TOK.get(px));
          if (k < 0) throw new Error('badge colour outside its ramp');
          return String(k);
        }).join(''),
      ),
    ];
  }),
);
write(
  'sprites.ts',
  `/**
 * Finance sprites. GENERATED by tools/pixel-art/finance/ship.js: edit the generator, not this file.
 * Rows of art pixels, one character per pixel, \`.\` = empty; SPRITE_LEGEND names the palette token
 * of each character. Badge shapes use the digits 0 to 4 for the steps of BADGE_RAMPS.
 */
export const SPRITE_LEGEND: Readonly<Record<string, string>> = ${J(Object.fromEntries([...tokChars].map(([t, c]) => [c, t])))};

/** One coin per market symbol, 16 by 16. */
export const COIN_ROWS = ${J(coins)} as const;

/** Auction gavel, 16 by 16: raised, then striking the block. */
export const GAVEL_FRAMES: readonly (readonly string[])[] = ${J(gavel)};

/** Dividend coin spin, 9 by 9, four frames. */
export const SPIN_FRAMES: readonly (readonly string[])[] = ${J(spin)};

/** Company badge outlines, 12 by 12, as ramp steps. */
export const BADGE_SHAPE_ROWS = ${J(shapes)} as const;
export type BadgeShape = keyof typeof BADGE_SHAPE_ROWS;

/** Badge colours: five palette steps each, dark to light. */
export const BADGE_RAMPS = ${J(Object.fromEntries(BADGE_HUES.map((h) => [h, BADGE_RAMPS[h]])))} as const;
export type BadgeHue = keyof typeof BADGE_RAMPS;

/** The kind glyph laid on a badge (7 by 6): \`a\` stem or handle, \`b\` leaf. */
export const BADGE_GLYPHS = ${J(GLYPHS)} as const;
`,
);

execFileSync('pnpm', ['exec', 'prettier', '--write', ...files], { cwd: root, stdio: 'ignore' });
for (const f of files) console.log(f, fs.statSync(path.join(root, f)).size);
