// Writes the shipped race sprite: apps/web/src/screens/horse/horse-art.ts (8 frames of 48 by 32 as
// role strings) and the colour variables in horse.css (between the horse-art markers). A frame
// does not know its coat: each character is a role (coat step, mane, points, silks, outline) and
// the CSS of a coat class and a silks class gives the roles their palette tokens.
//   node tools/pixel-art/horse/ship.js   (needs the reference plate, see tools/pixel-art/README.md)
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { P } from '../lib/env.js';
import { geometry, cut, parts, L } from './render.js';
import { COATS, SILKS } from '../lib/palette.js';

const W = 46,
  H = 30;
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const geo = geometry(W, H);

// role characters
const ROLE = 'abcdefghijklmnopqrstu'; // a-e coat steps c0..c4, f-h points, i-k tail, l-n mane, o hoof, p-r silks, s outline lit, t outline shade, u eye
const colourOf = (r) => P.col([ROLE.indexOf(r) * 11 + 5, 90, 200]);
const roleOf = new Map([...ROLE].map((r) => [colourOf(r), r]));

function frame(i) {
  const cells = cut(parts[i], W, H, geo);
  const buf = new P.Buf(W, H);
  for (let j = 0; j < H; j++)
    for (let k = 0; k < W; k++) {
      const c = cells[j * W + k];
      if (!c) continue;
      const raw = (c.v - 0.1) / 0.8;
      const v = P.clamp(raw < 0.55 ? 0.55 - (0.55 - raw) * 0.62 : raw);
      const band = (n, s = v) => P.band(s, n, k, j, 0.3);
      let r;
      switch (c.label) {
        case L.HOOF:
          r = 'o';
          break;
        case L.POINT:
          r = 'fgh'[band(3)];
          break;
        case L.MANE:
          r = 'lmn'[band(3)];
          break;
        case L.TAIL:
          r = 'ijk'[band(3)];
          break;
        case L.CAP:
          r = 'p';
          break;
        case L.RIDER:
          r = 'pqr'[band(3, v * 0.92)];
          break;
        default:
          r = 'bcde'[band(4)];
      }
      buf.px[j * W + k] = colourOf(r);
    }
  // eye: one head cell, a third of the way down and back (same rule as the preview)
  const heads = [];
  for (let j = 0; j < H; j++)
    for (let k = 0; k < W; k++) {
      const c = cells[j * W + k];
      if (c && c.label === L.HEAD) heads.push([k, j]);
    }
  if (heads.length >= 3) {
    const x0 = Math.min(...heads.map((p) => p[0])),
      x1 = Math.max(...heads.map((p) => p[0]));
    const y0 = Math.min(...heads.map((p) => p[1])),
      y1 = Math.max(...heads.map((p) => p[1]));
    const tx = x0 + (x1 - x0) * 0.3,
      ty = y0 + (y1 - y0) * 0.3;
    let best = null,
      bd = 1e9;
    for (const [k, j] of heads) {
      const d = (k - tx) ** 2 + (j - ty) ** 2;
      if (d < bd) {
        bd = d;
        best = [k, j];
      }
    }
    buf.px[best[1] * W + best[0]] = colourOf('u');
  }
  const out = P.selout(buf, colourOf('s'), colourOf('t'), { dir: [-1, -1] });
  const rows = [];
  for (let j = 0; j < out.h; j++) {
    let row = '';
    for (let k = 0; k < out.w; k++) {
      const px = out.px[j * out.w + k];
      row += px >>> 24 ? (roleOf.get(px) ?? '?') : '.';
    }
    rows.push(row);
  }
  if (rows.some((r) => r.includes('?'))) throw new Error('unmapped colour');
  return rows;
}
const frames = parts.map((_, i) => frame(i));

const ts = `/**
 * Race horse art. GENERATED by tools/pixel-art/horse/ship.js: edit the generator, not this file.
 * Eight frames of one gallop stride, 48 by 32 art pixels, one character per pixel, \`.\` = empty.
 * Characters are roles, not colours: a-e coat steps, f-h lower legs, i-k tail, l-n mane, o hoof,
 * p-r silks (cap, shade, light), s and t outline (lit side, shade), u eye. \`.hr-px-<char>\` in
 * horse.css fills each from the variables of the coat class and the silks class.
 * Reference: Eadweard Muybridge, The Horse in Motion (1878), public domain (see CREDITS.md).
 */
export const HORSE_ART_WIDTH = 48;
export const HORSE_ART_HEIGHT = 32;
export const HORSE_FRAMES: readonly (readonly string[])[] = ${JSON.stringify(frames)};
/** The frame shown when the horse stands still (stable, breeding): the stretched-out gallop. */
export const HORSE_STILL_FRAME = 3;
`;
fs.writeFileSync(path.join(root, 'apps/web/src/screens/horse/horse-art.ts'), ts);

// ---- CSS: coat and silks variables, role fills ----
const COAT_KEYS = Object.keys(COATS);
const dark = (key) => !!COATS[key].points || key === 'aoge';
const tk = (n) => `var(--${n})`;
function coatCss(key) {
  const c = COATS[key],
    lo = dark(key) ? 0 : 1,
    mane = c.mane,
    pts = c.points;
  const v = {};
  c.body.forEach((n, i) => (v[`c${i}`] = n));
  for (let k = 0; k < 3; k++) {
    v[`p${k}`] = pts ? pts[k] : c.body[1 + k];
    v[`t${k}`] = mane[lo + k];
    v[`n${k}`] = mane[Math.min(4, lo + 1 + k)];
  }
  v.hoof = pts ? 'neutral-6' : c.body[0];
  v.ol = key === 'aoge' ? 'neutral-35' : c.body[2];
  v.os = pts || key === 'aoge' || key === 'tochiguri' ? 'neutral-4' : c.body[0];
  v.eye = pts || key === 'aoge' || key === 'tochiguri' ? 'neutral-65' : 'neutral-6';
  return `.hr-coat-${key} {\n${Object.entries(v)
    .map(([k, n]) => `  --hr-${k}: ${tk(n)};`)
    .join('\n')}\n}\n`;
}
const silksCss = Object.entries(SILKS)
  .map(
    ([key, [a, b, c]]) =>
      `.hr-silks-${key} {\n  --hr-s0: ${tk(a)};\n  --hr-s1: ${tk(b)};\n  --hr-s2: ${tk(c)};\n}\n`,
  )
  .join('');
const FILL = {
  a: 'c0',
  b: 'c1',
  c: 'c2',
  d: 'c3',
  e: 'c4',
  f: 'p0',
  g: 'p1',
  h: 'p2',
  i: 't0',
  j: 't1',
  k: 't2',
  l: 'n0',
  m: 'n1',
  n: 'n2',
  o: 'hoof',
  p: 's0',
  q: 's1',
  r: 's2',
  s: 'ol',
  t: 'os',
  u: 'eye',
};
const fills = Object.entries(FILL)
  .map(([r, v]) => `.hr-px-${r} {\n  fill: var(--hr-${v});\n}\n`)
  .join('');
const block = `/* horse-art:begin (generated by tools/pixel-art/horse/ship.js) */\n${COAT_KEYS.map(coatCss).join('')}${silksCss}${fills}/* horse-art:end */`;
const cssPath = path.join(root, 'apps/web/src/screens/horse/horse.css');
let css = fs.readFileSync(cssPath, 'utf8');
if (!/horse-art:begin/.test(css)) throw new Error('markers missing in horse.css');
css = css.replace(/\/\* horse-art:begin[\s\S]*?horse-art:end \*\//, block);
fs.writeFileSync(cssPath, css);
console.log('frames', frames.length, frames[0].length + 'x' + frames[0][0].length);
// keep generated files in the repository's prettier style
execFileSync(
  'pnpm',
  [
    'exec',
    'prettier',
    '--write',
    'apps/web/src/screens/horse/horse-art.ts',
    'apps/web/src/screens/horse/horse.css',
  ],
  { cwd: root, stdio: 'ignore' },
);
