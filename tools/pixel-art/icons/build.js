// Writes the shipped icon data: packages/ui/src/pixel/icon-art.ts (row strings) and the fill rules
// in packages/ui/src/styles/bundle.css (between the pixel-icons markers). Run from the repo root:
//   node tools/pixel-art/icons/build.js && pnpm exec prettier --write packages/ui/src
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { P } from '../lib/env.js';
import { HEX } from '../lib/palette.js';
import { make } from './kit.js';
import './games.js';
import './more.js';
import './life.js';
import './stream.js';
import NAMES from './names.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const rgbToToken = new Map();
for (const [name, hex] of Object.entries(HEX)) {
  const key = P.col([1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)));
  if (!rgbToToken.has(key)) rgbToToken.set(key, name);
}
const CHARS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
const legend = new Map(); // token -> char
const icons = {};
for (const name of NAMES) {
  const { buf } = make(name);
  const rows = [];
  for (let y = 0; y < 16; y++) {
    let row = '';
    for (let x = 0; x < 16; x++) {
      const px = buf.px[y * 16 + x];
      if (!(px >>> 24)) {
        row += '.';
        continue;
      }
      const token = rgbToToken.get(px);
      if (!token) throw new Error(`${name}: colour at ${x},${y} is not a palette token`);
      if (!legend.has(token)) legend.set(token, CHARS[legend.size]);
      row += legend.get(token);
    }
    rows.push(row);
  }
  icons[name] = rows;
}
if (legend.size > CHARS.length) throw new Error('too many colours for one character each');

const ts = `/**
 * Game icon art. GENERATED by tools/pixel-art/icons/build.js: edit the generator, not this file.
 * 16 by 16 art pixels, one character per pixel, \`.\` = empty. Each character is a palette step:
 * \`.bb-px-<char>\` in bundle.css fills it from the token named in ICON_LEGEND, so the art follows
 * the theme and nothing here carries a colour value.
 */
export const GAME_ICON_NAMES = ${JSON.stringify(NAMES)} as const;
export type GameIconName = (typeof GAME_ICON_NAMES)[number];

export const GAME_ICON_ROWS: Readonly<Record<GameIconName, readonly string[]>> = ${JSON.stringify(icons)};

/** Character to palette token, the same table the stylesheet is built from. */
export const ICON_LEGEND: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries([...legend].map(([t, c]) => [c, t])))};
`;
fs.writeFileSync(path.join(root, 'packages/ui/src/pixel/icon-art.ts'), ts);

const cssPath = path.join(root, 'packages/ui/src/styles/bundle.css');
let css = fs.readFileSync(cssPath, 'utf8');
const rules = [...legend].map(([t, c]) => `.bb-px-${c} {\n  fill: var(--${t});\n}\n`).join('');
const block = `/* pixel-icons:begin (generated by tools/pixel-art/icons/build.js) */\n${rules}/* pixel-icons:end */`;
css = css.replace(/\/\* pixel-icons:begin[\s\S]*?pixel-icons:end \*\//, block);
fs.writeFileSync(cssPath, css);
console.log('icons', NAMES.length, 'colours', legend.size);
// keep generated files in the repository's prettier style
execFileSync(
  'pnpm',
  [
    'exec',
    'prettier',
    '--write',
    'packages/ui/src/pixel/icon-art.ts',
    'packages/ui/src/styles/bundle.css',
  ],
  { cwd: root, stdio: 'ignore' },
);
