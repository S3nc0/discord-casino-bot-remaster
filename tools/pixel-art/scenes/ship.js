// Writes the scene art the game ships: row strings per picture, a legend `char -> [light token,
// dark token]`, nothing else. Run from the repository root:
//   ART_REF=/some/folder/ref node tools/pixel-art/scenes/ship.js
// (the horse portrait needs the reference photo, see README.md). The files are formatted after.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { ROOT, encode, themed, tsModule } from './kit.js';
import { stand, lane, laneDark, innerRail, gate, dust } from './race.js';
import { stall, paddock, STALL_HEAD, PADDOCK_HEADS } from './stable.js';
import { portrait, withOutline, roleOf, PW } from './portrait.js';
import { pitFrames, PIT_SLOTS, PIT_FLOOR } from './arena.js';
import { FIGHTERS, fighter, outlined, FW, FH } from './fighters.js';
import { mine, MINER_X, MINE_FLOOR } from './mine.js';
import { miner, outlinedMiner, SWING, MH } from './miner.js';
import { find, ORES, RELICS } from './finds.js';
import { shopBanner, shelfTile, storeBanner, slotTile } from './shop.js';

const HEAD = (lines) => [
  ...lines,
  'GENERATED by tools/pixel-art/scenes/ship.js: edit the generator, not this file.',
  'Row strings, one character per art pixel, `.` = empty. The legend gives each character a',
  'palette token for the light theme and one for the dark theme, so nothing here is a colour value.',
];
const written = [];
function write(rel, header, arts, extra = '') {
  const file = path.join(ROOT, rel);
  let src = tsModule(HEAD(header), arts).replace(/^ {4}([^\w\s'])(: \[)/gm, "    '$1'$2");
  fs.writeFileSync(file, src + extra);
  written.push(file);
}
const js = (v) => JSON.stringify(v);

// ---- race ----
write(
  'apps/web/src/screens/horse/race-art.ts',
  [
    'Race track scenery: grandstand and sky behind the lanes, turf tiles with mowing stripes, the',
    'inner rail, the starting gate and the dust behind a galloping horse (four frames).',
  ],
  {
    RACE_STAND: themed(stand),
    RACE_LANE: themed(lane),
    RACE_LANE_DARK: themed(laneDark),
    RACE_RAIL: themed(innerRail),
    RACE_GATE: themed(gate),
    RACE_DUST: encode(dust('light'), dust('dark')),
  },
);

// ---- stable and breeding ----
const head = withOutline(portrait());
const rows = [];
for (let y = 0; y < head.h; y++) {
  let r = '';
  for (let x = 0; x < head.w; x++) r += roleOf(head.px[y * head.w + x]) ?? '.';
  rows.push(r);
}
write(
  'apps/web/src/screens/horse/stable-art.ts',
  [
    'Stall and paddock behind the horse portraits, each a back layer and a front layer (door, fence)',
    'that goes over the horse. Portrait made from a CC0 photograph (see CREDITS.md).',
  ],
  {
    STALL_BACK: themed((t) => stall(t).back),
    STALL_FRONT: themed((t) => stall(t).front),
    PADDOCK_BACK: themed((t) => paddock(t).back),
    PADDOCK_FRONT: themed((t) => paddock(t).front),
  },
  [
    '/** Horse head portrait facing left, the roles of horse-art.ts (`.hr-px-<char>`): coat, mane, halter in silks. */',
    `export const PORTRAIT_WIDTH = ${head.w};`,
    `export const PORTRAIT_HEIGHT = ${head.h};`,
    'export const PORTRAIT_ROWS: readonly string[] = [',
    ...rows.map((r) => `  '${r}',`),
    '];',
    '/** Where the portrait goes in the stall and in the paddock (top left, art pixels). */',
    `export const STALL_HEAD = ${js({ x: STALL_HEAD.x, y: STALL_HEAD.y })};`,
    `export const PADDOCK_HEADS = ${js({ left: PADDOCK_HEADS.left, right: PADDOCK_HEADS.right })};`,
    '',
  ].join('\n'),
);
void PW;

// ---- arena ----
const fighters = {};
FIGHTERS.forEach((f, i) => {
  fighters[`FIGHTER_${i}`] = encode(['idle', 'attack'].map((p) => outlined(fighter(f, p))));
  fighters[`FIGHTER_${i}_LEFT`] = encode(
    ['idle', 'attack'].map((p) => outlined(fighter(f, p, true))),
  );
});
write(
  'apps/web/src/screens/horse/arena-art.ts',
  [
    'Underground arena: the pit (three frames of torch flames) and the sixteen fighters, idle and',
    'attack frame each, facing right and facing left. Poses from Muybridge plate 336 (public domain).',
  ],
  { ARENA_PIT: encode(pitFrames()), ...fighters },
  [
    `export const FIGHTER_WIDTH = ${FW};`,
    `export const FIGHTER_HEIGHT = ${FH};`,
    '/** Top left of the fighter on the left and on the right in the pit (art pixels). */',
    `export const PIT_SPOTS = ${js({ left: { x: PIT_SLOTS.left - 17, y: PIT_FLOOR - FH + 2 }, right: { x: PIT_SLOTS.right - (FW - 17), y: PIT_FLOOR - FH + 2 } })};`,
    `export const FIGHTER_ART = [${FIGHTERS.map((_, i) => `[FIGHTER_${i}, FIGHTER_${i}_LEFT]`).join(', ')}] as const;`,
    '',
  ].join('\n'),
);

// ---- mine ----
const finds = Object.fromEntries(
  [...ORES, ...RELICS].map((id) => [`FIND_${id.toUpperCase()}`, encode(find(id))]),
);
write(
  'apps/web/src/screens/life/mine-art.ts',
  [
    'Mine: tunnel, ore cart and rock face (second frame: chips flying off the face), the miner swinging',
    'a pick (four frames, from Muybridge plate 385, public domain), and the ores and relics that come out of the rock.',
  ],
  {
    MINE: encode([mine(false), mine(true)]),
    MINER: encode(SWING.map((s) => outlinedMiner(miner(s)))),
    ...finds,
  },
  [
    `export const MINER_SPOT = ${js({ x: MINER_X, y: MINE_FLOOR - MH + 2 })};`,
    `export const FIND_ART = { ${[...ORES, ...RELICS].map((id) => `${id}: FIND_${id.toUpperCase()}`).join(', ')} } as const;`,
    '',
  ].join('\n'),
);

// ---- shop and inventory ----
write(
  'apps/web/src/screens/life/shop-art.ts',
  ['Shop: shelves of goods over a counter, and the shelf tile behind each item icon.'],
  { SHOP_BANNER: encode(shopBanner()), SHELF_TILE: encode(shelfTile()) },
);
write(
  'apps/web/src/screens/life/inventory-art.ts',
  ['Storeroom: crates, barrels and an open chest, and the slot tile behind each item icon.'],
  { STORE_BANNER: encode(storeBanner()), SLOT_TILE: encode(slotTile()) },
);

execFileSync('pnpm', ['exec', 'prettier', '--write', ...written], { cwd: ROOT, stdio: 'ignore' });
console.log(written.map((f) => `${path.relative(ROOT, f)} ${fs.statSync(f).size}`).join('\n'));
