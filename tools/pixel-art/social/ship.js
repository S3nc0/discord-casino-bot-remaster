/** The avatar placeholder: a dark bust on an indigo slot, drawn in code (no photo). */
function placeholder() {
  const b = new P.Buf(36, 36);
  const bg = ['indigo-30', 'indigo-20'].map((t) => P.col(tokOf(t)));
  for (let y = 0; y < 36; y++)
    for (let x = 0; x < 36; x++) b.px[y * 36 + x] = bg[P.band(y / 35, 2, x, y, 0.3)];
  const bust = prop(36, 36, (hi, part) => {
    const R = ['neutral-17', 'neutral-25', 'neutral-35', 'neutral-50', 'neutral-60'];
    const body = part(R, { round: 3.5, steps: [1, 2, 3] });
    hi.rrect(body, 6, 25, 24, 14, 7);
    const head = part(R, { round: 4, steps: [1, 2, 3] });
    hi.ellipse(head, 18, 15, 7.2, 7.6);
    const q = part('paper', { fixed: 3, outline: false });
    hi.cells(
      16,
      10,
      ['###', '#.#', '..#', '.#.', '...', '.#.'].map((r) => r),
      { '#': q },
    );
  });
  for (let i = 0; i < b.px.length; i++) if (bust.px[i] >>> 24) b.px[i] = bust.px[i];
  return b;
}
