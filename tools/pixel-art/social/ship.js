const HEAD = (lines) => [
  ...lines,
  'GENERATED by tools/pixel-art/social/ship.js: edit the generator, not this file.',
  'Row strings, one character per art pixel, `.` = empty. The legend gives each character a',
  'palette token (light theme, dark theme), so nothing here is a colour value.',
];
const written = [];
function write(rel, header, arts, extra = []) {
  const file = path.join(ROOT, rel);
  const src = tsModule(HEAD(header), arts).replace(/^ {4}([^\w\s'])(: \[)/gm, "    '$1'$2");
  fs.writeFileSync(file, src + (extra.length ? extra.join('\n') + '\n' : ''));
  written.push(file);
}
const one = (buf) => encode(buf);
const crop = (frames, r) => frames.map((f) => P.crop(f, r.x, r.y, r.w, r.h));
/** The smallest box holding every pixel that differs from `still` in any frame: the overlay. */
function changed(still, frames) {
  let x0 = Infinity,
    y0 = Infinity,
    x1 = -1,
    y1 = -1;
  for (const f of frames)
    for (let i = 0; i < f.px.length; i++)
      if (f.px[i] !== still.px[i]) {
        const x = i % still.w,
          y = Math.floor(i / still.w);
        x0 = Math.min(x0, x);
        y0 = Math.min(y0, y);
        x1 = Math.max(x1, x);
        y1 = Math.max(y1, y);
      }
  return { x: x0, y: y0, w: x1 - x0 + 1, h: y1 - y0 + 1 };
}
